-- One compatibility report per (source_version, target_version) pair.
-- Aggregates endpoint-level results into an overall classification.
CREATE TABLE IF NOT EXISTS compatibility_reports (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_session_id         BIGINT NOT NULL,
    source_version_id        BIGINT NOT NULL,
    target_version_id        BIGINT NOT NULL,
    -- COMPATIBLE | PARTIALLY_COMPATIBLE | INCOMPATIBLE
    compatibility_status     VARCHAR(30) NOT NULL,
    overall_score            DOUBLE PRECISION NOT NULL,
    -- Counts for explainability
    total_source_fields      INT NOT NULL DEFAULT 0,
    matched_fields           INT NOT NULL DEFAULT 0,
    unmatched_required_fields INT NOT NULL DEFAULT 0,
    auto_approved_count      INT NOT NULL DEFAULT 0,
    requires_review_count    INT NOT NULL DEFAULT 0,
    low_confidence_count     INT NOT NULL DEFAULT 0,
    -- Human-readable explanation of the classification decision
    explanation              TEXT,
    created_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cr_session FOREIGN KEY (match_session_id)
        REFERENCES semantic_match_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_src FOREIGN KEY (source_version_id)
        REFERENCES api_versions(id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_tgt FOREIGN KEY (target_version_id)
        REFERENCES api_versions(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_cr_session  ON compatibility_reports(match_session_id);
CREATE INDEX IF NOT EXISTS idx_cr_src_ver  ON compatibility_reports(source_version_id);

-- One result per (source_endpoint, target_endpoint) pair within a report.
-- Provides the per-endpoint breakdown required by the spec.
CREATE TABLE IF NOT EXISTS endpoint_compatibility_results (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id                 BIGINT NOT NULL,
    source_endpoint_id        BIGINT NOT NULL,
    target_endpoint_id        BIGINT NOT NULL,
    source_endpoint_path      VARCHAR(500),
    target_endpoint_path      VARCHAR(500),
    -- COMPATIBLE | PARTIALLY_COMPATIBLE | INCOMPATIBLE
    compatibility_status      VARCHAR(30) NOT NULL,
    compatibility_score       DOUBLE PRECISION NOT NULL,
    -- Field-level counts for explainability
    total_source_fields       INT NOT NULL DEFAULT 0,
    matched_required_fields   INT NOT NULL DEFAULT 0,
    unmatched_required_fields INT NOT NULL DEFAULT 0,
    matched_optional_fields   INT NOT NULL DEFAULT 0,
    unmatched_optional_fields INT NOT NULL DEFAULT 0,
    -- Serialised JSON arrays of field names for the breakdown view
    -- e.g. ["name","mobile","email"]
    matched_field_paths       TEXT,
    unmatched_source_paths    TEXT,
    unmatched_target_paths    TEXT,
    -- Human-readable reason
    explanation               TEXT,
    created_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ecr_report FOREIGN KEY (report_id)
        REFERENCES compatibility_reports(id) ON DELETE CASCADE,
    CONSTRAINT fk_ecr_src_ep FOREIGN KEY (source_endpoint_id)
        REFERENCES endpoints(id) ON DELETE CASCADE,
    CONSTRAINT fk_ecr_tgt_ep FOREIGN KEY (target_endpoint_id)
        REFERENCES endpoints(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ecr_report     ON endpoint_compatibility_results(report_id);
CREATE INDEX IF NOT EXISTS idx_ecr_src_ep     ON endpoint_compatibility_results(source_endpoint_id);
