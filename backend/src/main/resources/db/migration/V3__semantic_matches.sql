-- One session per (source_version, target_version) analysis run.
-- Stores overall compatibility score and classification.
CREATE TABLE IF NOT EXISTS semantic_match_sessions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_version_id     BIGINT NOT NULL,
    target_version_id     BIGINT NOT NULL,
    status                VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    -- PENDING | RUNNING | COMPLETED | FAILED
    compatibility_status  VARCHAR(30),
    -- COMPATIBLE | PARTIALLY_COMPATIBLE | INCOMPATIBLE
    overall_score         DOUBLE PRECISION,
    embedding_provider    VARCHAR(100),
    embedding_model       VARCHAR(200),
    field_pair_count      INT DEFAULT 0,
    error_message         TEXT,
    created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at          TIMESTAMP,
    CONSTRAINT fk_sms_src FOREIGN KEY (source_version_id)
        REFERENCES api_versions(id) ON DELETE CASCADE,
    CONSTRAINT fk_sms_tgt FOREIGN KEY (target_version_id)
        REFERENCES api_versions(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_sms_src ON semantic_match_sessions(source_version_id);
CREATE INDEX IF NOT EXISTS idx_sms_tgt ON semantic_match_sessions(target_version_id);

-- One candidate per (source_field, target_field) pair within a session.
-- Stores the raw cosine similarity, context factors, and final confidence.
CREATE TABLE IF NOT EXISTS semantic_match_candidates (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id           BIGINT NOT NULL,
    source_field_id      BIGINT NOT NULL,
    target_field_id      BIGINT NOT NULL,
    -- Paths stored redundantly for quick query without joins
    source_path          VARCHAR(500),
    target_path          VARCHAR(500),
    source_normalized    VARCHAR(1000),
    target_normalized    VARCHAR(1000),
    -- Scores
    cosine_similarity    DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    type_factor          DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    path_factor          DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    confidence           DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    -- Approval status
    approval_status      VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    -- PENDING | AUTO_APPROVED | REQUIRES_REVIEW | REJECTED | LOW_CONFIDENCE
    notes                TEXT,
    created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_smc_session FOREIGN KEY (session_id)
        REFERENCES semantic_match_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_smc_src_field FOREIGN KEY (source_field_id)
        REFERENCES schema_fields(id) ON DELETE CASCADE,
    CONSTRAINT fk_smc_tgt_field FOREIGN KEY (target_field_id)
        REFERENCES schema_fields(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_smc_session ON semantic_match_candidates(session_id);
CREATE INDEX IF NOT EXISTS idx_smc_confidence ON semantic_match_candidates(confidence DESC);
