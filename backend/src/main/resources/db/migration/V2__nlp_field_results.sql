-- =========================================================
-- V2__nlp_field_results.sql
-- NLP pipeline output table (Phase 5)
-- Stores preprocessed field name representations for
-- consumption by the semantic matching engine (Phase 6).
-- =========================================================

CREATE TABLE IF NOT EXISTS nlp_field_results (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schema_field_id  BIGINT NOT NULL,
    original_name    VARCHAR(255) NOT NULL,
    field_path       VARCHAR(500) NOT NULL,
    raw_tokens       TEXT,           -- JSON array string: ["phone","number"]
    expanded_tokens  TEXT,           -- JSON array string: ["mobile","number"]
    normalized       VARCHAR(1000),  -- "mobile number"
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_nlp_schema_field FOREIGN KEY (schema_field_id)
        REFERENCES schema_fields(id) ON DELETE CASCADE,
    CONSTRAINT uq_nlp_schema_field UNIQUE (schema_field_id)
);

CREATE INDEX IF NOT EXISTS idx_nlp_schema_field_id
    ON nlp_field_results(schema_field_id);
