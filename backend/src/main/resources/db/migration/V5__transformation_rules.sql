-- V5__transformation_rules.sql
-- Transformation Rule Generator tables (Phase 8)
-- =========================================================

-- One transformation rule per accepted MatchCandidate.
-- Rules are structured data only — no executable code stored here.
--
-- Operation values (§ 6.8):
--   RENAME          — name → fullName (flat-to-flat, different names)
--   MOVE            — mobile → contact.phone (flat-to-nested)
--   FLATTEN         — contact.phone → phoneNumber (nested-to-flat)
--   COMBINE         — firstName + lastName → fullName (n-to-1)
--   SPLIT           — fullName → firstName + lastName (1-to-n)
--   TYPE_CONVERSION — "21" → 21  (same path, different type)
--   ENUM_MAPPING    — "male" → "M" (explicit enum value mapping)
--
-- Rule status lifecycle (Phase 8 only produces GENERATED / INVALID):
--   GENERATED → APPROVED (Phase 9)
--   GENERATED → REJECTED (Phase 9, or user via REST)
--   GENERATED → INVALID  (failed Phase 8 safety validation)
--
-- candidate_status mirrors the Phase 6 approval_status that produced this rule.
-- A REQUIRES_REVIEW candidate → GENERATED rule (must NOT be auto-approved here).
-- An AUTO_APPROVED candidate → GENERATED rule eligible for auto-approval in Phase 9.

CREATE TABLE IF NOT EXISTS transformation_rules (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Link back to the Phase 7 report that triggered generation
    report_id               BIGINT NOT NULL,

    -- The Phase 6 candidate this rule was derived from (1:1 for simple rules)
    match_candidate_id      BIGINT,

    -- Endpoint pair this rule applies to
    source_endpoint_id      BIGINT NOT NULL,
    target_endpoint_id      BIGINT NOT NULL,

    -- Redundant copies for fast lookup without joins
    source_endpoint_path    VARCHAR(600),
    target_endpoint_path    VARCHAR(600),

    -- Primary source/target field paths (dot-notation, e.g. "contact.phone")
    -- For COMBINE: source_path is the primary source; additional sources in source_paths
    -- For SPLIT:   target_path is the primary target; additional targets in target_paths
    source_path             VARCHAR(500),
    target_path             VARCHAR(500),

    -- JSON arrays for multi-field operations
    -- COMBINE: ["firstName","lastName"]  (all source paths including the primary)
    -- SPLIT:   ["firstName","lastName"]  (all target paths including the primary)
    source_paths            TEXT,
    target_paths            TEXT,

    -- Transformation operation (see values above)
    operation               VARCHAR(30) NOT NULL,

    -- Data types from Phase 4 schema analysis ("string","integer","number","boolean","object","array","unknown")
    source_type             VARCHAR(50),
    target_type             VARCHAR(50),

    -- Confidence score preserved from Phase 6 (never inflated here)
    confidence              DOUBLE PRECISION NOT NULL DEFAULT 0.0,

    -- Phase 6 approval status of the source candidate
    -- Values: AUTO_APPROVED | REQUIRES_REVIEW
    candidate_status        VARCHAR(30) NOT NULL,

    -- Phase 8 rule lifecycle status
    -- Values: GENERATED | APPROVED | REJECTED | INVALID
    rule_status             VARCHAR(20) NOT NULL DEFAULT 'GENERATED',

    -- JSON object for operation-specific parameters:
    --   RENAME:          {} (no extra params needed)
    --   MOVE/FLATTEN:    {} (paths carry all info)
    --   TYPE_CONVERSION: {"from":"string","to":"integer"}
    --   ENUM_MAPPING:    {"mappings":{"male":"M","female":"F"}}
    --   COMBINE:         {"separator":" ","order":["firstName","lastName"]}
    --   SPLIT:           {"separator":" ","targets":["firstName","lastName"]}
    parameters              TEXT,

    -- Populated when rule_status = REJECTED
    rejection_reason        TEXT,

    -- Populated when rule_status = INVALID (semicolon-separated list of errors)
    validation_errors       TEXT,

    created_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_tr_report FOREIGN KEY (report_id)
        REFERENCES compatibility_reports(id) ON DELETE CASCADE,
    CONSTRAINT fk_tr_candidate FOREIGN KEY (match_candidate_id)
        REFERENCES semantic_match_candidates(id) ON DELETE SET NULL,
    CONSTRAINT fk_tr_src_ep FOREIGN KEY (source_endpoint_id)
        REFERENCES endpoints(id) ON DELETE CASCADE,
    CONSTRAINT fk_tr_tgt_ep FOREIGN KEY (target_endpoint_id)
        REFERENCES endpoints(id) ON DELETE CASCADE
);

-- Fast lookup by report (most common query — generate + list)
CREATE INDEX IF NOT EXISTS idx_tr_report       ON transformation_rules(report_id);

-- Fast lookup by endpoint pair (Phase 9/10 runtime query)
CREATE INDEX IF NOT EXISTS idx_tr_ep_pair      ON transformation_rules(source_endpoint_id, target_endpoint_id);

-- Fast filtering by status
CREATE INDEX IF NOT EXISTS idx_tr_status       ON transformation_rules(rule_status);

-- Fast lookup by candidate (for idempotency checks)
CREATE INDEX IF NOT EXISTS idx_tr_candidate    ON transformation_rules(match_candidate_id);
