-- =========================================================
-- V1__init.sql
-- Initial schema for Semantic API Compatibility Framework
-- H2 (local dev) and PostgreSQL (Docker) compatible
-- =========================================================

-- Table: apis
CREATE TABLE IF NOT EXISTS apis (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Table: api_versions
CREATE TABLE IF NOT EXISTS api_versions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_id      BIGINT NOT NULL,
    version     VARCHAR(50) NOT NULL,
    base_url    VARCHAR(500),
    description TEXT,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_api_versions_api FOREIGN KEY (api_id) REFERENCES apis(id) ON DELETE CASCADE,
    CONSTRAINT uq_api_version UNIQUE (api_id, version)
);

-- Table: endpoints
CREATE TABLE IF NOT EXISTS endpoints (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_version_id  BIGINT NOT NULL,
    http_method     VARCHAR(10) NOT NULL,
    path            VARCHAR(500) NOT NULL,
    description     TEXT,
    request_schema  TEXT,
    response_schema TEXT,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_endpoints_api_version FOREIGN KEY (api_version_id) REFERENCES api_versions(id) ON DELETE CASCADE
);

-- Table: schema_fields
CREATE TABLE IF NOT EXISTS schema_fields (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_id     BIGINT NOT NULL,
    schema_type     VARCHAR(20) NOT NULL,
    field_name      VARCHAR(255) NOT NULL,
    field_path      VARCHAR(500) NOT NULL,
    field_type      VARCHAR(50),
    is_required     BOOLEAN NOT NULL DEFAULT FALSE,
    parent_path     VARCHAR(500),
    description     TEXT,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_schema_fields_endpoint FOREIGN KEY (endpoint_id) REFERENCES endpoints(id) ON DELETE CASCADE
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_api_versions_api_id ON api_versions(api_id);
CREATE INDEX IF NOT EXISTS idx_endpoints_api_version_id ON endpoints(api_version_id);
CREATE INDEX IF NOT EXISTS idx_schema_fields_endpoint_id ON schema_fields(endpoint_id);
